-- EduClass database starter for Supabase (PostgreSQL)
-- Review and run in Supabase SQL Editor. RLS is enabled on all app tables.
-- Admin/teacher role assignment should be done by a trusted administrator,
-- not by allowing users to update their own role.

create type public.educlass_role as enum ('student', 'teacher', 'admin');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  class_name text not null default 'XI',
  role public.educlass_role not null default 'student',
  created_at timestamptz not null default now()
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  content text not null default '',
  sort_order integer not null default 0,
  published boolean not null default false,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table public.assignments (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  due_at timestamptz,
  max_score integer not null default 100 check (max_score between 1 and 1000),
  published boolean not null default false,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  answer_text text not null,
  submitted_at timestamptz not null default now(),
  score numeric(5,2) check (score between 0 and 100),
  teacher_feedback text,
  graded_by uuid references public.profiles(id),
  unique (assignment_id, student_id)
);

create table public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  questions jsonb not null default '[]'::jsonb,
  published boolean not null default false,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table public.quiz_attempts (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  answers jsonb not null default '{}'::jsonb,
  score numeric(5,2) check (score between 0 and 100),
  submitted_at timestamptz not null default now()
);

create table public.attendance (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  class_date date not null default current_date,
  status text not null check (status in ('present','late','absent','excused')),
  note text,
  recorded_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  unique (student_id, class_date)
);

create table public.discussion_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 3000),
  created_at timestamptz not null default now()
);

-- Create a profile automatically for each newly registered auth user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Role helper. The role field must only be changed by a trusted admin process.
create or replace function public.current_role()
returns public.educlass_role
language sql stable security definer
set search_path = ''
as $$
  select role from public.profiles where id = auth.uid()
$$;

alter table public.profiles enable row level security;
alter table public.lessons enable row level security;
alter table public.assignments enable row level security;
alter table public.submissions enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.attendance enable row level security;
alter table public.discussion_posts enable row level security;

-- Profiles: users can see their own profile; teachers/admins can see class profiles.
create policy "profile read own or staff" on public.profiles for select to authenticated
using (id = auth.uid() or public.current_role() in ('teacher','admin'));
create policy "profile update own name" on public.profiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid());

-- Published learning content is visible to signed-in users; staff manage content.
create policy "read published lessons" on public.lessons for select to authenticated
using (published or public.current_role() in ('teacher','admin'));
create policy "staff insert lessons" on public.lessons for insert to authenticated
with check (public.current_role() in ('teacher','admin'));
create policy "staff update lessons" on public.lessons for update to authenticated
using (public.current_role() in ('teacher','admin')) with check (public.current_role() in ('teacher','admin'));
create policy "staff delete lessons" on public.lessons for delete to authenticated
using (public.current_role() in ('teacher','admin'));

create policy "read published assignments" on public.assignments for select to authenticated
using (published or public.current_role() in ('teacher','admin'));
create policy "staff manage assignments" on public.assignments for all to authenticated
using (public.current_role() in ('teacher','admin')) with check (public.current_role() in ('teacher','admin'));

-- Students see and create their own submissions; staff can review and grade.
create policy "read own submissions or staff" on public.submissions for select to authenticated
using (student_id = auth.uid() or public.current_role() in ('teacher','admin'));
create policy "student submit own work" on public.submissions for insert to authenticated
with check (student_id = auth.uid());
create policy "student update own ungraded work" on public.submissions for update to authenticated
using (student_id = auth.uid() and score is null)
with check (student_id = auth.uid() and score is null);
create policy "staff grade submissions" on public.submissions for update to authenticated
using (public.current_role() in ('teacher','admin'))
with check (public.current_role() in ('teacher','admin'));

create policy "read published quizzes" on public.quizzes for select to authenticated
using (published or public.current_role() in ('teacher','admin'));
create policy "staff manage quizzes" on public.quizzes for all to authenticated
using (public.current_role() in ('teacher','admin')) with check (public.current_role() in ('teacher','admin'));

create policy "read own quiz attempts or staff" on public.quiz_attempts for select to authenticated
using (student_id = auth.uid() or public.current_role() in ('teacher','admin'));
create policy "student create own quiz attempts" on public.quiz_attempts for insert to authenticated
with check (student_id = auth.uid());

create policy "student read own attendance or staff" on public.attendance for select to authenticated
using (student_id = auth.uid() or public.current_role() in ('teacher','admin'));
create policy "staff manage attendance" on public.attendance for all to authenticated
using (public.current_role() in ('teacher','admin')) with check (public.current_role() in ('teacher','admin'));

create policy "read discussion posts" on public.discussion_posts for select to authenticated using (true);
create policy "authenticated create own post" on public.discussion_posts for insert to authenticated
with check (author_id = auth.uid());
create policy "author or staff delete post" on public.discussion_posts for delete to authenticated
using (author_id = auth.uid() or public.current_role() in ('teacher','admin'));

